        public static int Run(string[] args)
        {
            string dir = args.Length > 1 ? Path.GetFullPath(args[1]) : Export.DefaultDir("reports");
            Directory.CreateDirectory(dir);
            EconomyCatalog cat = SimFx.Catalog;
            Tuning t = SimFx.Tuning;
            var sb = new StringBuilder();
            Header(sb, cat, t);
            Loop(sb, SimEngine.DefaultLadderLines.Length);
            Changes(sb);
            ResourceTable(sb, cat);
            RecipeTable(sb, cat);
            StructureTable(sb, cat);
            ToolTable(sb, cat);
            UpgradeAndResearch(sb, cat);
            TravelSection(sb, cat, t);
            EraSection(sb, cat);
            LadderSection(sb, cat);
            StarterLoopSection(sb, cat);
            ShardSection(sb, cat);
            ObstacleSection(sb, cat);
            ScoreSection(sb, cat, t);
            TuningSection(sb, t);
            Risks(sb);
            File.WriteAllText(Path.Combine(dir, "ECONOMY.md"), sb.ToString());
            Console.WriteLine("ECONOMY.md written to " + dir + " (" + sb.Length + " characters)");
            return 0;
        }

        static void Header(StringBuilder sb, EconomyCatalog cat, Tuning t)
        {
            sb.AppendLine("# Frontier economy: design summary");
            sb.AppendLine();
            sb.AppendLine("Generated by `run.ps1 report` from the catalog and the balance simulator (catalog schema " + cat.schemaVersion + ", content " + cat.contentVersion + ", " + t.Count + " tuning keys, tuning digest `" + t.Digest().ToString("x") + "`). Every table below is produced from the data, so it cannot drift from `data\\*.json`. Companion files: `ATLAS_TEXT.md` (codex text), `ICON_BRIEF.md` (icon artist brief), `TUNING_KEYS.md` (every knob), `INTEGRATION.md` (how to import it into Unity), `PROGRESS.md` (build log), charts `chart_*.png`.");
            sb.AppendLine();
            sb.AppendLine("Contents: " + cat.resources.Length + " resources, " + cat.recipes.Length + " recipes, " + cat.structures.Length + " structures, " + cat.tools.Length + " tool ladders x 7 tiers, " + cat.upgrades.Length + " upgrades, " + cat.research.Length + " research nodes, " + cat.obstacles.Length + " obstacle kinds, one shard economy, one score formula.");
            sb.AppendLine();
        }

        static void Loop(StringBuilder sb, int ladderLines)
        {
            sb.AppendLine("## 1. The loop in one page");
            sb.AppendLine();
            sb.AppendLine("1. **Start small.** The pack holds 9 slots, so the first Warehouse comes in the first minutes. Wood, stone and scrap are chopped, mined and salvaged by hand; the Refinery turns wood into fuel and planks.");
            sb.AppendLine("2. **Fuel is the leash.** Travel costs fuel (`legFuel = 1.5 + 0.14 x ly^1.1`, one leg per Hyperspace Run, refund up to 40 % for a perfect run). Jump range is an upgrade, so early on only a handful of systems are reachable; each jump level opens a ring of the map.");
            sb.AppendLine("3. **Deeper worlds, better tiers.** Planet tier grows with distance (`floor(1.6 x log2(1 + d/60))`); tier gates resources (iron at 1, titanium and crystal at 2, helium-3 and cores at 3, radium at 4, dark matter at 6), hazards and the hull plating needed to land.");
            sb.AppendLine("4. **Everything advanced is built from the basics.** Steel is iron plate and planks; planks are wood; biocomposite, thermal alloy and void alloy chain down to wood, stone and scrap again. A late project therefore needs tens of thousands of tier-0 units: the player keeps returning to the starter worlds, but every tool tier (x1.0 to x12.5), camp level and megaproject bonus makes the same mini-game pay more, so the return trip is an evening, not a month.");
            sb.AppendLine("5. **Time only on build jobs.** Gathering, refining and crafting are instant (crafting is batched per tap). Build, upgrade and clear jobs have builder timers (instant at first, a day at most for ordinary jobs, 2 to 10 days per megaproject stage). Nova Shards skip timers, buy builders and cosmetics; they never buy resources, combat power or score.");
            sb.AppendLine("6. **A next shiny thing at every step.** The goal ladder (section 10) lists " + ladderLines + " headline wants; the simulator checks that a regular player always completes something or visibly advances a megaproject within the era's limit.");
            sb.AppendLine();
        }

