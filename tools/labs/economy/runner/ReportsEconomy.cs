        // ------------------------------------------------------------------------------------------------ resources
        static void ResourceTable(StringBuilder sb, EconomyCatalog cat)
        {
            sb.AppendLine("## 3. Resources (" + cat.resources.Length + ")");
            sb.AppendLine();
            sb.AppendLine("Value is in scrap-equivalents (used for score weights, shard sanity checks and cost generation). Stack is items per backpack or warehouse slot. Tier-0 volume is the number of wood/stone/scrap units one item ultimately costs.");
            sb.AppendLine();
            var rows = new List<string[]>();
            foreach (ResourceDef r in cat.resources)
            {
                string methods = r.harvestMethods == null ? "crafted" : string.Join("/", Array.ConvertAll(r.harvestMethods, m => m.ToString()));
                rows.Add(new[] { "`" + r.id + "`", r.displayName, r.category.ToString(), r.tier.ToString(), methods, ReportData.Value(r.baseValue), r.stackSize.ToString(), cat.Prices.T0Volume(r.id).ToString("0.#"), ShortObtain(cat, r) });
            }
            ReportData.Table(sb, new[] { "id", "name", "category", "tier", "method", "value", "stack", "tier-0 volume", "how to obtain" }, rows);
            sb.AppendLine("Full codex entries (description, how to obtain, used in) are in `ATLAS_TEXT.md`; icon concepts and colours in `ICON_BRIEF.md`.");
            sb.AppendLine();
        }

        static string ShortObtain(EconomyCatalog cat, ResourceDef r)
        {
            string s = ReportData.Obtain(cat, r);
            return s.Length > 150 ? s.Substring(0, 147) + "..." : s;
        }

        static void RecipeTable(StringBuilder sb, EconomyCatalog cat)
        {
            sb.AppendLine("## 4. Recipes (" + cat.recipes.Length + ")");
            sb.AppendLine();
            sb.AppendLine("All crafting is instant. Value ratio = value out / value in; it never exceeds the tier ceiling (1.10 to 1.35, rising with tier) and no explicit bonus recipe ships, so the recipe graph cannot mint free value (a test checks every recipe and every cycle).");
            sb.AppendLine();
            var rows = new List<string[]>();
            foreach (RecipeDef r in cat.recipes)
            {
                double vin = cat.Prices.Value(r.inputs), vout = cat.Prices.Value(r.outputs);
                rows.Add(new[] { r.displayName, cat.Structure(r.stationId).displayName + " L" + r.stationLevel, "T" + r.tier, ReportData.Items(cat, r.inputs), ReportData.Items(cat, r.outputs), (vout / vin).ToString("0.00"), r.unlockResearch ?? "start" });
            }
            ReportData.Table(sb, new[] { "recipe", "station", "tier", "inputs", "outputs", "ratio", "research" }, rows);
            sb.AppendLine("Tier-0 volume per item (wood-equivalents): planks " + cat.Prices.T0Volume("planks").ToString("0.#") + ", iron plate " + cat.Prices.T0Volume("iron_plate").ToString("0.#") + ", steel " + cat.Prices.T0Volume("steel").ToString("0.#")
                + ", biocomposite " + cat.Prices.T0Volume("biocomposite").ToString("0.#") + ", thermal alloy " + cat.Prices.T0Volume("thermal_alloy").ToString("0.#") + ", void alloy " + cat.Prices.T0Volume("void_alloy").ToString("0.#")
                + ", warp coil " + cat.Prices.T0Volume("warp_coil").ToString("0.#") + ", antimatter " + cat.Prices.T0Volume("antimatter").ToString("0.#") + ". Mid and late recipes therefore demand large tier-0 volume.");
            sb.AppendLine();
        }

        // ------------------------------------------------------------------------------------------------ structures
        static void StructureTable(StringBuilder sb, EconomyCatalog cat)
        {
            sb.AppendLine("## 5. Structures (" + cat.structures.Length + ")");
            sb.AppendLine();
            sb.AppendLine("Cost is the value in scrap-equivalents of the level's ingredients (the exact lines are in `data\\structures.json`); time is the builder timer of that level. Footprint is building slots; planets have 12, 16, 24, 36, 48 or 64 slots by size class. Effect is the level's primary effect (see the kind column); megaprojects are installment projects (cost per stage).");
            sb.AppendLine();
            var rows = new List<string[]>();
            foreach (StructureDef s in cat.structures)
            {
                string c1 = Cost(cat, s, 1), c5 = Cost(cat, s, 5), c10 = Cost(cat, s, s.maxLevel >= 10 ? 10 : s.maxLevel);
                string t1 = Time(s, 1), t5 = Time(s, 5), t10 = Time(s, Math.Min(10, s.maxLevel));
                string e1 = Eff(s, 1), e10 = Eff(s, Math.Min(10, s.maxLevel));
                rows.Add(new[] { "`" + s.id + "`", s.displayName, s.role.ToString(), "T" + s.tier, s.footprint.ToString(), s.maxLevel.ToString(), c1, c5, c10, t1, t5, t10, s.effectKind + ": " + e1 + " -> " + e10, s.unlockResearch ?? "-" });
            }
            ReportData.Table(sb, new[] { "id", "name", "role", "tier", "fp", "max L", "cost L1", "cost L5", "cost L10", "time L1", "time L5", "time L10", "effect (L1 -> L10)", "research" }, rows);
            sb.AppendLine("Level 1 cost lines of the early structures: " + string.Join("; ", new[] { Lines(cat, "lumber"), Lines(cat, "mine"), Lines(cat, "warehouse"), Lines(cat, "refinery"), Lines(cat, "alarm"), Lines(cat, "fabricator"), Lines(cat, "foundry") }) + ".");
            sb.AppendLine();
        }

        static string Lines(EconomyCatalog cat, string id)
        {
            StructureDef s = cat.Structure(id);
            return s.displayName + " " + (s.levels[0].cost.Length == 0 ? "free" : ReportData.Items(cat, s.levels[0].cost));
        }

        static string Cost(EconomyCatalog cat, StructureDef s, int level)
        {
            if (level > s.maxLevel) return "-";
            ItemAmount[] c = s.levels[level - 1].cost;
            return c.Length == 0 ? "free" : ReportData.Value(cat.Prices.Value(c));
        }

        static string Time(StructureDef s, int level)
        {
            if (level > s.maxLevel) return "-";
            return ReportData.Seconds(s.levels[level - 1].buildSeconds);
        }

        static string Eff(StructureDef s, int level)
        {
            StructureLevelDef l = s.levels[level - 1];
            string e = l.effect.ToString("0.###");
            if (s.capacityKind != null && s.capacityKind.Length > 0 && l.capacity > 0) e += " (" + s.capacityKind + " " + l.capacity + ")";
            return e;
        }

        // ------------------------------------------------------------------------------------------------ tools
        static void ToolTable(StringBuilder sb, EconomyCatalog cat)
        {
            sb.AppendLine("## 6. Tool ladders (6 x 7 tiers)");
            sb.AppendLine();
            sb.AppendLine("Every ladder shares the yield multiplier curve (x1.0, 1.6, 2.4, 3.6, 5.4, 8.2, 12.5) and the run-time multiplier curve; tiers differ in what they cost (resources plus alloys) and what they require (reach tier, research, Research Lab level). The multiplier applies to the harvest reward of every mini-game the ladder serves; the base yield curve stays `0.4 + 1.1 x quality`.");
            sb.AppendLine();
            foreach (ToolLadderDef l in cat.tools)
            {
                sb.AppendLine("**" + l.displayName + "** (serves " + string.Join(", ", Array.ConvertAll(l.games, g => g.ToString())) + ")");
                sb.AppendLine();
                var rows = new List<string[]>();
                foreach (ToolTierDef d in l.tiers)
                    rows.Add(new[] { d.tier.ToString(), d.displayName, "x" + d.yieldMult.ToString("0.#"), "x" + d.runTimeMult.ToString("0.##"), d.cost.Length == 0 ? "owned at start" : ReportData.Value(cat.Prices.Value(d.cost)), "T" + d.requiresReachTier, "L" + d.requiresLabLevel, d.researchPrereq ?? "-", d.cost.Length == 0 ? "-" : ReportData.Items(cat, d.cost) });
                ReportData.Table(sb, new[] { "tier", "name", "yield", "run time", "cost value", "reach", "lab", "research", "cost lines" }, rows);
            }
        }

        // ------------------------------------------------------------------------------------------------ upgrades and research
        static void UpgradeAndResearch(StringBuilder sb, EconomyCatalog cat)
        {
            sb.AppendLine("## 7. Ship, defense and logistics upgrades (" + cat.upgrades.Length + ") and research (" + cat.research.Length + " nodes)");
            sb.AppendLine();
            var rows = new List<string[]>();
            foreach (UpgradeDef u in cat.upgrades)
            {
                UpgradeLevelDef a = u.levels[0], z = u.levels[u.levels.Length - 1];
                rows.Add(new[] { "`" + u.id + "`", u.displayName, u.group.ToString(), u.maxLevel.ToString(), u.effect + ": " + a.value.ToString("0.##") + " -> " + z.value.ToString("0.##"), ReportData.Value(cat.Prices.Value(a.cost)), ReportData.Value(cat.Prices.Value(z.cost)), "T" + a.requiresReachTier + " -> T" + z.requiresReachTier });
            }
            ReportData.Table(sb, new[] { "id", "name", "group", "levels", "effect", "L1 cost", "last cost", "reach" }, rows);
            sb.AppendLine("Hull plating is one upgrade per hazard (heat, cold, toxic, radiation, void) with 3 levels; a world needs plating level 1, 2 or 3 (from planet tier 5 and 9) for every hazard it has, and plating level N itself needs reach tier, so the ship upgrades follow the map outward.");
            sb.AppendLine();
            var branches = new List<string>();
            int minLab = int.MaxValue, maxLab = 0;
            foreach (ResearchNodeDef n in cat.research) { if (!branches.Contains(n.branch)) branches.Add(n.branch); minLab = Math.Min(minLab, n.labLevel); maxLab = Math.Max(maxLab, n.labLevel); }
            sb.AppendLine("Research is a " + cat.research.Length + "-node tree in " + branches.Count + " branches (" + string.Join(", ", branches) + ") gated by Research Lab level (" + minLab + " to " + maxLab + "); a node's cost is paid in resources, never in time. Nodes per tier: " + string.Join(", ", ResearchCounts(cat)) + ".");
            sb.AppendLine();
            var rrows = new List<string[]>();
            foreach (ResearchNodeDef n in cat.research)
                rrows.Add(new[] { "`" + n.id + "`", n.displayName, n.branch, "T" + n.tier, "L" + n.labLevel, ReportData.Value(cat.Prices.Value(n.cost)), n.prereqs.Length == 0 ? "-" : string.Join(", ", n.prereqs), string.Join(", ", n.unlocks) });
            ReportData.Table(sb, new[] { "id", "name", "branch", "tier", "lab", "cost value", "prerequisites", "unlocks" }, rrows);
        }

        static List<string> ResearchCounts(EconomyCatalog cat)
        {
            var counts = new SortedDictionary<int, int>();
            foreach (ResearchNodeDef n in cat.research) { int c; counts.TryGetValue(n.tier, out c); counts[n.tier] = c + 1; }
            var list = new List<string>();
            foreach (KeyValuePair<int, int> kv in counts) list.Add("tier " + kv.Key + ": " + kv.Value);
            return list;
        }

        // ------------------------------------------------------------------------------------------------ travel
        static void TravelSection(StringBuilder sb, EconomyCatalog cat, Tuning t)
        {
            sb.AppendLine("## 8. Travel");
            sb.AppendLine();
            var travel = new TravelModel(t, cat);
            var rules = new WorldRules(cat, new UniverseConfig());
            sb.AppendLine("`routeFuel = (legs x 1.5 + 0.14 x routeLy^1.1) x engineFactor x (1 + 0.2 x cargoFill) x (1 - discounts) x (autopilot 1.6)`; the route length is the straight distance x 1.15 detour, split into the fewest legs that stay below 90 % of the jump range; each leg is one Hyperspace Run (25 to 90 s) that refunds up to 40 % of its fuel by performance. Landing needs hull plating >= the world's requirement for each of its hazards. Fuel cells are 1 energy, plasma 8, antimatter 64.");
            sb.AppendLine();
            var jrows = new List<string[]>();
            UpgradeDef jump = cat.Upgrade("jump"), engine = cat.Upgrade("engine");
            for (int i = 0; i < jump.levels.Length; i++)
                jrows.Add(new[] { (i + 1).ToString(), jump.levels[i].displayName, jump.levels[i].value.ToString("0") + " ly", i < engine.levels.Length ? engine.levels[i].displayName + " x" + engine.levels[i].value.ToString("0.##") : "-", jump.levels[i].researchPrereq ?? "-", ReportData.Value(cat.Prices.Value(jump.levels[i].cost)) });
            ReportData.Table(sb, new[] { "level", "jump drive", "range", "engine (same level)", "research", "jump cost value" }, jrows);
            var trows = new List<string[]>();
            for (int tier = 0; tier <= 11; tier++)
            {
                double d = rules.DistanceForTier(tier);
                var cells = new List<string> { tier.ToString(), d.ToString("0") + " ly", rules.DangerForTier(tier).ToString("0.0"), "plating " + travel.RequiredPlatingLevel(tier) };
                foreach (int eng in new[] { 0, 5, 10 })
                {
                    int jl = 1;
                    while (jl < jump.levels.Length && travel.JumpRangeLy(jl) < Math.Max(d, 1.0)) jl++;
                    TripPlan p = travel.PlanInterSystem(Math.Max(d, 10.0), jl, eng, 0.5, 0.0, false);
                    cells.Add(p.fuel + " (" + p.hops + " legs, jump L" + jl + ")");
                }
                trows.Add(cells.ToArray());
            }
            ReportData.Table(sb, new[] { "tier", "starts at", "danger", "landing", "fuel one way, engine 0", "engine 5", "engine 10" }, trows);
            sb.AppendLine("Tier, danger and reward come from `WorldRules` (`TierForDistance`, `DistanceForTier`, `DangerForTier`, `RunYield`), which reuse the universe generator's own tier formula and danger constants; richer deposits and higher danger pay more per run, and the same run pays `tool multiplier x (1 + camp bonus)` more each time the player upgrades.");
            sb.AppendLine();
        }
